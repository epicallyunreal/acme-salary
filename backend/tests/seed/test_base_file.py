"""The committed base file agrees with the seed, row by row, like the golden hash (F9, D72)."""

from datetime import datetime
from decimal import Decimal
from pathlib import Path

import pytest
from openpyxl import load_workbook

from apps.compensation.validators import template_columns
from apps.imports.management.commands.make_import_file import base_rows, profile_codes
from seed import profiles

BASE_FILE = Path(__file__).resolve().parents[3] / "sample-data" / "base-15000.xlsx"


def cell(value):
    if isinstance(value, datetime):
        return value.date()
    if isinstance(value, int | float):
        return Decimal(str(value))
    return value


@pytest.mark.slow
def test_the_base_file_is_the_seed_row_by_row():
    """Regenerated by the same commit whenever the seed changes: `make_import_file --base`."""
    expected = base_rows(profiles.ACTIVE_EMPLOYEES, profiles.EXITED_EMPLOYEES, 42)
    columns = template_columns(profile_codes())
    values = load_workbook(BASE_FILE, read_only=True).worksheets[0].iter_rows(values_only=True)

    assert list(next(values)) == columns
    count = 0
    for row, want in zip(values, expected, strict=True):
        got = dict(zip(columns, (cell(value) for value in row), strict=True))
        for column in columns:
            assert got[column] == want.get(column), (count + 2, column, got[column])
        count += 1
    assert count == profiles.ACTIVE_EMPLOYEES + profiles.EXITED_EMPLOYEES
